/**
 * Remove sequências que costumam virar □ no Windows:
 * - ZWJ (profissões, famílias: 🧑‍💻)
 * - tom de pele
 * - tags regionais extras
 */
function isDisplaySafeEmoji(e: string): boolean {
  if (!e || !e.trim()) return false;
  if (e.includes("\u200D")) return false; // ZWJ
  if (e.includes("\u200C")) return false;
  // skin tone modifiers
  if (/[\u{1F3FB}-\u{1F3FF}]/u.test(e)) return false;
  // keycap base + combining (sometimes tofu)
  if (e.includes("\u20E3") && e.length > 3) return false;
  return true;
}

